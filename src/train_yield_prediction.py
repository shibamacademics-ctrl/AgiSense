import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import joblib
import json
from sklearn.model_selection import train_test_split,GridSearchCV
from sklearn.preprocessing import OneHotEncoder,StandardScaler
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.linear_model import LinearRegression
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error,mean_squared_error,r2_score
from xgboost import XGBRegressor

NUMERIC_FEATURES = ["Year", "average_rain_fall_mm_per_year", "pesticides_tonnes", "avg_temp"]
CATEGORICAL_FEATURES = ["Area", "Item"]
TARGET = "hg/ha_yield"

def load_data():
  df = pd.read_csv("yield_df.csv")
  x = df[NUMERIC_FEATURES + CATEGORICAL_FEATURES]
  y = df[TARGET]
  return x,y
def preprocessor():
  return ColumnTransformer(
      transformers=[
          ("num",StandardScaler(),NUMERIC_FEATURES),
          ("cat",OneHotEncoder(handle_unknown="ignore"),CATEGORICAL_FEATURES)
      ]
  )
def evaluate(y_true,y_pred,model_name):
  rmse = np.sqrt(mean_squared_error(y_true,y_pred))
  mae = mean_absolute_error(y_true,y_pred)
  r2 = r2_score(y_true,y_pred)
  print(f"{model_name} RMSE: {rmse}")
  print(f"{model_name} MAE: {mae}")
  print(f"{model_name} R2: {r2}")
  return {"rmse" : rmse, "mae" : mae, "r2" : r2}
def Actual_vs_pred(y_true,y_pred,model_name):
  plt.figure(figsize=(6,6))
  plt.scatter(y_true,y_pred,alpha=0.2,s=8)
  lims = [min(y_true.min(), y_pred.min()), max(y_true.max(), y_pred.max())]
  plt.plot(lims, lims, "r--", linewidth=1)
  plt.xlabel("Actual Yield (hg/ha)")
  plt.ylabel("Predicted Yield (hg/ha)")
  plt.title(f"{model_name}: Actual vs Predicted")
  plt.tight_layout()
  plt.show()
def main():
  x,y = load_data()
  x_train,x_test,y_train,y_test = train_test_split(x,y,test_size=0.2,random_state=42)
  results = {}
  print("\n----Linear Regression----\n")
  lr_pipeline = Pipeline([
      ("preprocessor",preprocessor()),
      ("model",LinearRegression())
  ])
  lr_pipeline.fit(x_train,y_train)
  lr_preds = lr_pipeline.predict(x_test)
  results["Linear Regression"] = evaluate(y_test,lr_preds,"Linear Regression")
  Actual_vs_pred(y_test,lr_preds,"Linear Regression")
  joblib.dump(lr_pipeline,"lr_pipeline.pkl")

  print("\n----Random Forest Regressor----\n")
  rf_configs = [
        {"n_estimators": 50, "max_depth": 10},
        {"n_estimators": 100, "max_depth": 15},
    ]
  best_rf_r2 = -np.inf
  best_rf_pipeline = None
  best_rf_params = None
  for cfg in rf_configs:
      pipe = Pipeline([
          ("preprocess", preprocessor()),
          ("model", RandomForestRegressor(random_state=42, n_jobs=1, **cfg)),
        ])
      pipe.fit(x_train, y_train)
      preds = pipe.predict(x_test)
      r2 = r2_score(y_test, preds)
      print(f"  config {cfg} -> R2: {r2:.4f}")
      if r2 > best_rf_r2:
          best_rf_r2 = r2
          best_rf_pipeline = pipe
          best_rf_params = cfg
  rf_preds = best_rf_pipeline.predict(x_test)
  print("Best RF params:", best_rf_params)
  results["Random Forest"] = evaluate(y_test, rf_preds, "Random Forest")
  results["Random Forest"]["best_params"] = best_rf_params
  Actual_vs_pred(y_test, rf_preds, "Random Forest")
  joblib.dump(best_rf_pipeline, "rf_pipeline.pkl")

  print("\n----XGBoost Regressor----\n")
  xgb_configs = [
        {"n_estimators": 100, "max_depth": 4, "learning_rate": 0.2},
        {"n_estimators": 100, "max_depth": 6, "learning_rate": 0.1},
    ]
  best_xgb_r2 = -np.inf
  best_xgb_pipeline = None
  best_xgb_params = None
  for cfg in xgb_configs:
      pipe = Pipeline([
          ("preprocess", preprocessor()),
          ("model", XGBRegressor(random_state=42, n_jobs=1, **cfg)),
        ])
      pipe.fit(x_train, y_train)
      preds = pipe.predict(x_test)
      r2 = r2_score(y_test, preds)
      print(f"  config {cfg} -> R2: {r2:.4f}")
      if r2 > best_xgb_r2:
          best_xgb_r2 = r2
          best_xgb_pipeline = pipe
          best_xgb_params = cfg
  xgb_preds = best_xgb_pipeline.predict(x_test)
  print("Best XGB params:", best_xgb_params)
  results["XGBoost"] = evaluate(y_test, xgb_preds, "XGBoost")
  results["XGBoost"]["best_params"] = best_xgb_params
  Actual_vs_pred(y_test, xgb_preds, "XGBoost")
  joblib.dump(best_xgb_pipeline, "xgb_pipeline.pkl")

  def get_feature_names(pipeline):
        preprocessor = pipeline.named_steps["preprocess"] if "preprocess" in pipeline.named_steps else pipeline["preprocess"]
        num_names = NUMERIC_FEATURES
        cat_encoder = preprocessor.named_transformers_["cat"]
        cat_names = list(cat_encoder.get_feature_names_out(CATEGORICAL_FEATURES))
        return num_names + cat_names


  for model_name, best_pipeline in [("Random Forest", best_rf_pipeline), ("XGBoost", best_xgb_pipeline)]:
        feature_names = get_feature_names(best_pipeline)
        importances = best_pipeline.named_steps["model"].feature_importances_
        agg = {}
        for name, imp in zip(feature_names, importances):
            if name in NUMERIC_FEATURES:
                agg[name] = agg.get(name, 0) + imp
            else:
                base = "Area" if name.startswith("Area_") else "Item"
                agg[base] = agg.get(base, 0) + imp

        agg_sorted = dict(sorted(agg.items(), key=lambda x: x[1], reverse=True))
        plt.figure(figsize=(7, 4))
        sns.barplot(x=list(agg_sorted.values()), y=list(agg_sorted.keys()))
        plt.title(f"{model_name} Feature Importance (aggregated)")
        plt.xlabel("Importance")
        plt.tight_layout()
        plt.show()

        results[model_name]["feature_importance_aggregated"] = agg_sorted
  with open(f"yield_model_comparison.json", "w") as f:
        json.dump(results, f, indent=2, default=str)
  print("\n" + "=" * 50)
  print("SUMMARY")
  print("=" * 50)
  for name in ["Linear Regression", "Random Forest", "XGBoost"]:
    r = results[name]
    print(
        f"{name:20s} "
        f"RMSE: {r['rmse']:.1f} | "
        f"MAE: {r['mae']:.1f} | "
        f"R2: {r['r2']:.4f}"
    )

main()

















